import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const indices=['price-action-context-v1.js','selection-evidence-v1.js','selection-data-v2.js','structure-reversal-core-v1.js','structure-reversal-scanner-v1.js','structure-reversal-ui-v1.js'].map(n=>html.indexOf(`<script src="./${n}?`));
assert(indices.every(i=>i!==-1),'index.html 必須載入全部第六套依賴');
assert(indices.every((i,k)=>!k||i>indices[k-1]),'第六套依賴腳本順序錯誤');
const ctx=vm.createContext({console,Date,Map,Set,Object,Array,JSON,Number,String,Error,Intl,setTimeout,clearTimeout});
function load(name){vm.runInContext(fs.readFileSync(path.join(root,name),'utf8'),ctx,{filename:name});}
for(const name of ['price-action-context-v1.js','selection-evidence-v1.js','selection-data-v2.js','scan-exclusions-rsi-v5328.js','structure-reversal-config-v1.js','structure-reversal-core-v1.js','structure-reversal-scanner-v1.js','strong-stock-filter-v47.js'])load(name);
assert.equal(typeof ctx.ShitouSelectionEvidenceV1.date,'function');
assert.equal(typeof ctx.ShitouPriceActionV1.evaluate,'function');
assert.equal(typeof ctx.ShitouStructureScanner.scan,'function');
const target='2026-10-22';
const ms=Date.parse(target+'T00:00:00Z');
let days=[];for(let d=ms;days.length<75;d-=86400000){const day=new Date(d).getUTCDay();if(day!==0&&day!==6)days.push(new Date(d).toISOString().slice(0,10));}
days=days.reverse();
const dailySeries=days.map((date,i)=>({date,open:50+i*.1,high:51+i*.1,low:49+i*.1,close:50.5+i*.1,volume:1000000}));
const last=dailySeries.at(-1);
const q={code:'2330',name:'測試股',market:'TWSE',securityType:'COMMON_STOCK',ordinaryStockVerified:true,industryCode:'05',industryName:'電機機械',open:last.open,high:last.high,low:last.low,close:last.close,volume:1000000,tradeValue:70000000,quoteDate:target};
const meta={targetTradeDate:target,completedTradeDate:target,expectedTradeDate:target,twseQuoteDate:target,tpexQuoteDate:target,marketCoverageReady:true,industryCoverageReady:true,snapshotTimelinessReady:true,exclusionCoverageReady:true,exclusionDate:target,companySourcesReady:{twse:true,tpex:true},ordinaryValidTotal:1000,total:1000};
const bundle={meta,map:new Map([['2330',q]]),sectorMap:new Map([['2330',{...q}]]),snapshotRows:1000};
const F=ctx.ShitouStrongStockFilterV47;
assert.equal(F.validateMarket(meta,1000,new Date('2026-10-22T11:00:00Z')).ok,true,'完成交易日應通過市場檢查');
assert.equal(ctx.ShitouSelectionDataV2.inspectSnapshot(bundle).ok,true,'合法的市場快照應通過資料完整性檢查');
ctx.ShitouSelectionDataV2.bind(bundle);
const plan=ctx.ShitouStructureScanner.pool(bundle);
assert.equal(plan.items.length,1,'測試股票應進入第六套分析');
const report={stock:'2330',code:'2330',market:'TWSE',closeDate:target,completed:true,close:last.close,dailySeries,expectedTradingDates:days,priceAdjustment:{verified:true},volumeUnit:'shares'};
const scan=await ctx.ShitouStructureScanner.scan({plan,release:'V50-STRUCTURE-DEP.1',fetchBatch:async part=>ctx.ShitouSelectionDataV2.harmonize(part,{type:'MOMENTUM_DEEP_SCAN',results:[{ok:true,code:'2330',data:report}]},'DAILY_ONLY')});
assert.equal(scan.attempted,1);
assert.equal(scan.complete,true,'完整單檔 A/B 模擬掃描應結束');
assert.equal(scan.results.A.length,1);
assert.equal(scan.results.B.length,1);
assert.notEqual(scan.results.A[0].status,'DATA','A模式不可將有效歷史誤判成資料不足');
assert.notEqual(scan.results.B[0].status,'DATA','B模式不可將有效歷史誤判成資料不足');
assert.notEqual(scan.results.A[0].status,'EXCLUDED','A模式不得錯誤排除測試普通股');
ctx.ShitouStructureScanner.assertSnapshot(scan);
console.log('PASS STRUCTURE-DEP.1 | dependency order + date + verified daily cache + A/B scan');
